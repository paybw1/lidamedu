/**
 * 사건번호 패턴.
 * ★조·항·호·목·항의·조의 는 사건번호 부호가 아니다 — 제외하지 않으면 조문 표기를
 *   사건번호로 잡아 "원문에 없는 인용" 오탐이 쏟아진다.
 */
export const CASE_NO_RE = /\b\d{2,4}(?!조|항|호|목)[가-힣]{1,3}\d+\b/g;

/** 교재 근거 없이 쓰면 안 되는 단정형 — CLAUDE.md Non-negotiable 11. */
export const ASSERTIONS = [
  /통설은[^.]{0,30}이다/,
  /종전\s*판례는/,
  /다수설/,
  /학계의?\s*일반적인?\s*견해/,
];

/**
 * 답안 본문에 쓰면 안 되는 강학상 분류용어(법령·판례가 쓰지 않는 학설상 명칭).
 * ★"주지관용기술의 부가·삭제·변경" 을 넣었다가 4건 전부 오탐이었다(2026-08-22) —
 *   이건 강학상 용어가 아니라 **대법원이 쓰는 판시 문구**다(확대된 선출원 §29③ 의
 *   발명 동일성 판단 법리). 넣지 말 것.
 */
export const ACADEMIC_TERMS = ["주합발명", "조합발명"];

/** 사실관계 칸에 있으면 안 되는 **이 사건의** 판단·결론 표현. */
export const VERDICT_IN_FACTS = [
  /법원은[^.]{0,40}판단하[였였]/,
  /쟁점은/,
  /결론적으로/,
];

/**
 * 원문 대조용 정규화 — 공백을 전부 지운다.
 * ★판결문 전문은 줄바꿈이 공백으로 들어와 "특허법원 2019허  8033호" 처럼 사건번호
 *   가운데가 벌어져 있는 경우가 흔하다. 정확일치로 보면 실재하는 인용을 없는 것으로 잡는다.
 */
export const flatten = (s) => String(s ?? "").replace(/\s+/g, "");

/**
 * 유효한 사건부호 화이트리스트.
 * ★블랙리스트(조·항·호·목 제외)로는 부족했다 — "제29조의2" 의 "29의2" 가 사건번호로 잡혀
 *   조문 표기가 대량 오탐이 됐다(2026-09-01 전수 점검에서 "95의2" 17곳·"99의2" 50곳).
 *   부호는 유한 집합이므로 화이트리스트가 맞다.
 */
export const CASE_MARKS = new Set([
  // 대법원
  "후", "다", "도", "두", "마", "카", "므", "그", "오", "초", "재다", "재후", "허",
  // 하급심(민사·형사·행정·가사·신청)
  "가합", "가단", "가소", "나", "라", "고합", "고단", "고정", "노", "로",
  "구합", "구단", "누", "카합", "카단", "카기", "즈합", "즈단", "비", "드합", "드단",
]);

/** 특허심판원 심판번호 부호 — 법원 판결이 아니라 외부 판례 DB 조회 대상이 아니다. */
export const TRIAL_MARKS = new Set(["당", "원", "정", "취", "소", "재"]);

/** 사건번호 문자열에서 부호만 뽑는다("2009후3919" → "후"). */
export const markOf = (no) =>
  String(no ?? "").replace(/^\d+/, "").replace(/\d+$/, "");

/** 진짜 법원 사건번호로 볼 수 있는가(부호 화이트리스트). */
export const isCourtCaseNo = (no) => CASE_MARKS.has(markOf(no));
