export function allTexts() {
  const out = [TITLE];
  const walk = (it) => {
    if (typeof it === "string") return out.push(it);
    if (it.add) return; // 보충은 원본 대조 대상이 아니다
    out.push(it.was ?? it.t);
    (it.c ?? []).forEach(walk);
  };
  for (const b of BRANCHES) { out.push(String(b.no)); out.push(b.name); b.items.forEach(walk); }
  out.push(...DROPPED);
  return out;
}
