let updated = 0, inserted = 0;
for (const [oldTitle, title, screenKey, ord, body] of GUIDES) {
  if (oldTitle) {
    const { data, error } = await sb
      .from("guide_articles")
      .update({ title, category: CAT, body_md: body, display_order: ord, ...(screenKey ? { screen_key: screenKey } : {}) })
      .eq("title", oldTitle)
      .select("guide_id");
    if (error) throw error;
    if (data.length > 0) { updated++; continue; }
    // 구제목 미발견(이미 개명됨) — 새 제목으로 재시도
    const { data: d2, error: e2 } = await sb
      .from("guide_articles")
      .update({ category: CAT, body_md: body, display_order: ord })
      .eq("title", title)
      .select("guide_id");
    if (e2) throw e2;
    if (d2.length > 0) { updated++; continue; }
    console.log("!! 매칭 실패:", oldTitle);
  } else {
    const { data: ex } = await sb.from("guide_articles").select("guide_id").eq("title", title);
    if (ex && ex.length > 0) {
      await sb.from("guide_articles").update({ category: CAT, body_md: body, display_order: ord }).eq("title", title);
      updated++;
      continue;
    }
    const { error } = await sb.from("guide_articles").insert({
      title,
      category: CAT,
      body_md: body,
      screen_key: screenKey,
      display_order: ord,
      is_published: true,
      audience: "student",
    });
    if (error) throw error;
    inserted++;
  }
}
console.log(`완료 — 갱신 ${updated}, 신규 ${inserted}`);
