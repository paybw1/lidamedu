/** 긴 꼬리말이 짧은 것에 가려지지 않게 길이 내림차순. */
const TAILS = [...RAW_TAILS].sort((a, b) => b.length - a.length);
/**
 * 떼고 남는 머리말의 최소 길이.
 * ★1 로 둔다 — 「피청구인」은 "피 / 청구인" 이 옳고, 2 로 막으면 아예 못 나뉘어
 *   "피청 / 구인" 으로 잘린다.
 */
const MIN_HEAD = 1;
const HANGUL_ONLY = /^[가-힣]+$/;

/** 한 낱말을 형태소 단위로 나눈다. 나눌 데가 없으면 통째로 돌려준다. */
/**
 * 뒤에 붙는 조사·「등/들」과 한 글자 접미사「업」 — 떼어 두고 나눈 뒤 마지막 조각에
 * 되붙인다(보안서비스업 → 보안 / 서비스업, 대상상표들 → 대상 / 상표들).
 */
const PARTICLE = /(과의|등|들|업|와|과|를|을|의|로)$/;

function splitWord(word: string): string[] {
  if (!HANGUL_ONLY.test(word) || word.length < 4) return [word];
  const out: string[] = [];
  let head = word;
  for (;;) {
    const tail = TAILS.find(
      (t) => head.length - t.length >= MIN_HEAD && head.endsWith(t),
    );
    if (!tail) break;
    out.unshift(tail);
    head = head.slice(0, head.length - tail.length);
  }
  // ★꼬리말 사전이 먼저다. 조사를 먼저 떼면 「선출원주의」가 「주의」의 끝 "의" 에 걸려
  //   "선출 / 원주의" 로 갈린다(도해 전수 점검 2026-08-23에서 발견).
  //   사전에 하나도 안 걸렸을 때만 조사를 떼어 본다.
  if (out.length === 0) {
    const pm = PARTICLE.exec(word);
    if (pm) {
      const body = word.slice(0, word.length - pm[1].length);
      if (body.length >= 4) {
        const parts = splitWord(body);
        if (parts.length > 1)
          return [...parts.slice(0, -1), parts[parts.length - 1] + pm[1]];
      }
    }
  }
  // 머리말이 한 글자만 남고 뒤가 여럿이면 앞 조각에 붙인다 — 「부 / 등록 / 사유」 보다
  // 「부등록 / 사유」 가 낫다. (뒤가 하나뿐이면 「피 / 청구인」 이 옳으므로 그대로 둔다)
  if (head.length === 1 && out.length > 1) {
    out[0] = head + out[0];
    head = "";
  }
  // 사전에 안 걸리는 넉 자 한자어는 2+2 로 나눈다 — 「권리소진」·「하자해소」처럼
  // 두 형태소가 붙은 말이 대부분이다.
  // ★조사(…등)나 한 글자 접미사(…적·형·성·권·자·인·죄·효)로 끝나면 넣지 않는다 —
  //   「출원료등」이 "출원 / 료등", 「비상업적」이 "비상 / 업적", 「반폐쇄형」이
  //   "반폐 / 쇄형" 으로 잘못 갈린다.
  if (
    out.length === 0 &&
    head.length === 4 &&
    !PARTICLE.test(head) &&
    !/[적형성권자인죄효]$/.test(head)
  )
    return [head.slice(0, 2), head.slice(2)];
  return head ? [head, ...out] : out;
}

/**
 * 라벨 한 줄 → 줄바꿈 기회로 나눈 조각들. 조각 사이에 <wbr> 을 넣어 그린다.
 * 빗금(/·ㆍ) 뒤에서도 끊을 수 있게 한다 — 「결정/심결」처럼 붙여 쓴 라벨이 많다.
 */
export function labelSegments(
  line: string,
  opts: { perChar?: boolean } = {},
): string[] {
  const out: string[] = [];
  let buf = "";
  for (const ch of line) {
    buf += ch;
    if (ch === "/" || ch === "·" || ch === "ㆍ") {
      out.push(buf);
      buf = "";
    }
  }
  if (buf) out.push(buf);
  // ★더 나눌 뜻 경계가 없는 3자 한 덩어리(객체적·주체적·시기적·청구인)는 글자마다 끊을
  //   자리를 둔다 — 칸이 한 글자만 담으면 세로로 쌓이고, 두 글자를 담으면 「주체 / 적」이
  //   된다(원장 지시 2026-08-23). 여러 조각으로 이미 나뉜 라벨은 건드리지 않는다 —
  //   「적법성 / 심리」의 앞 조각까지 쪼개면 「심리」가 갈라질 수 있다.
  //   ★열 폭이 원본 비율로 고정된 표(도해)에서만 켠다. 내용에 따라 폭이 자동 배분되는
  //     표(마크다운 해설)에서 켜면 최소 폭이 한 글자까지 내려가 열이 찌그러진다.
  const perChar = (segs: string[]) =>
    opts.perChar && segs.length === 1 && /^[가-힣]{3}$/.test(segs[0])
      ? [...segs[0]]
      : segs;
  return out.flatMap((part) => {
    // 끝의 빗금은 떼어 두고 나눈 뒤 되붙인다 — 붙어 있으면 한글이 아니라 안 나뉜다.
    const sep = /[/·ㆍ]$/.test(part) ? part.slice(-1) : "";
    const body = sep ? part.slice(0, -1) : part;
    const back = (parts: string[]) =>
      sep ? [...parts.slice(0, -1), parts[parts.length - 1] + sep] : parts;
    // ★글자 단위(perChar)는 **라벨 전체가 한 낱말일 때만** 쓴다. 낱말마다 걸면
    //   「특허를 받을 수 있는 발명」이 "특 / 허 / 를 …" 로 산산이 흩어진다
    //   (객관식 해설 표 실물 확인 2026-08-23).
    const words = body.split(" ");
    if (words.length === 1) return back(perChar(splitWord(words[0])));
    // 낱말마다 따로 나눈다. 공백은 앞 조각 끝에 붙여 원문 글자를 그대로 보존한다
    // (공백 자체가 이미 줄바꿈 기회다).
    const segs: string[] = [];
    words.forEach((word, i) => {
      if (i > 0) segs[segs.length - 1] += " ";
      segs.push(...splitWord(word));
    });
    return back(segs);
  });
}
