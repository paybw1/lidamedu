// 운영자 입력 보조용 — aggressive reflow. 줄바꿈 없이 붙은 모든 넘버링 앞에 단락 구분.
// 학생 화면에서는 절대 호출하지 않는다.
//
// 패턴:
//   1. 2. 3. …        →  \d+\.\s
//   가. 나. 다. …      →  [가-힣]\.\s
//   1) 2) 3) …        →  \d+\)\s
//   가) 나) 다) …      →  [가-힣]\)\s
//   (1) (2) (3) …     →  \(\d+\)\s
//   (가) (나) (다) …   →  \([가-힣]+\)\s
//
// 이미 줄 시작에 있는 넘버링은 `[^\n]` 매처가 보호한다.
//
// 자동 보호 (lookbehind):
//   - "2019. 12. 24." 같은 날짜 안의 마침표는 분리하지 않는다 — 직전이 `\d+\.\s` 패턴이면 차단.
//   - "(1) (2)" 처럼 연속된 괄호 인덱스도 보호 — 직전이 `\(\d+\)\s` 면 차단.
//   - "1) 2)" 도 동일 — 직전이 `\d+\)\s` 면 차단.
//   - 사건번호("2017후523") 안에는 마침표가 없어 별도 보호 불필요.
export function reflowNumbering(text: string): string {
  // 한글 list marker 는 표준 14자(가/나/다/라/마/바/사/아/자/차/카/타/파/하)만 매칭.
  // 이전 `[가-힣]`/`[가-힣]+` 범위는 "전의 것) 제46조" 같은 일반 단어+`)` 도 매칭해
  // 잘못된 줄바꿈을 유발(2007다65245 사례).
  // paragraph numbering 1~99 만 매칭(`\d{1,2}`) — 4자리 연도("2019.")는 자동 제외.
  // 추가 lookbehind 보호:
  //   - 날짜 month/day("12. 24.") — 직전이 숫자(`(?<![\d.])`) 또는 "숫자+마침표+공백"(`(?<!\d\.\s)`) 차단
  //   - "(1)" 안 "1)" — 직전이 "(" 면 차단 (괄호 인덱스의 일부, 5번째 패턴이 처리)
  //   - 일반 문장 끝 "되었다." 의 "다" — 한글 list marker 보호: 직전이 한글(`(?<![가-힣])`) 이면 차단
  //   - 연속 괄호 인덱스 "(1) (2) (3)" — 이미 `(?<!\(\d+\)\s)` 로 차단
  const patterns: RegExp[] = [
    /([^\n])(?<![\d.])(?<!\d\.\s)\s*(?=\d{1,2}\.\s)/g,
    /([^\n])(?<![가-힣])\s*(?=[가나다라마바사아자차카타파하]\.\s)/g,
    /([^\n])(?<![\d.(])(?<!\d\)\s)\s*(?=\d{1,2}\)\s)/g,
    /([^\n])(?<![가-힣(])\s*(?=[가나다라마바사아자차카타파하]\)\s)/g,
    /([^\n])(?<!\(\d+\)\s)\s*(?=\(\d{1,2}\)\s)/g,
    /([^\n])\s*(?=\([가나다라마바사아자차카타파하]\)\s)/g,
  ];
  let out = text;
  for (const p of patterns) {
    out = out.replace(p, "$1\n\n");
  }
  return out;
}

// 학생 화면 자동 reflow 안전 버전.
//
// 두 가지 패턴에서 단락 분리한다:
//
// (1) 한국어 글자 뒤 한 자리 넘버링 (1.~9. / 가. / 1)~9) / (1)~(9) / (가)~(힣))
//     → "...있다. 1. 어쩌고" ✓ / "2007. 12. 1. 선고" ✗ (앞이 숫자) / "2015. 2017." ✗ (4자리)
//
// (2) (넘버링) + 짧은 소제목 + 공백 + 본문 — 운영자가 소제목과 본문을 한 줄에 입력한 경우.
//     소제목 단어: 판단 / 결론 / 사실관계 / 검토.
//     → "(2) 판단 그러나 원고들의 주장은…" → "판단" 뒤에 단락 분리.
//     좌측 lookbehind 가 (넘버링 + 공백 + 소제목 단어) 조합을 요구하므로 "법원의 판단이…"
//     같은 일반 본문은 매칭되지 않는다.
//
// 두 안전장치 공통: 이미 줄 시작인 패턴은 lookahead 가 자연스럽게 보호.
// 한글 list marker — 표준 14자(가/나/다/라/마/바/사/아/자/차/카/타/파/하)만 매칭.
// 이전 `[가-힣]` 범위는 "전의 것) 제46조" 같은 일반 단어+`)` 까지 매칭해 잘못된 줄바꿈을
// 유발했음(2007다65245 사례). lookbehind 의 `[가-힣)\]]` 는 그대로 — "이전 한글 글자(앞)"
// 은 모든 한글이 와도 OK.
const NUMBERING_RX =
  /(?<=[가-힣)\]]\.?)\s+(?=(?:\d\.|[가나다라마바사아자차카타파하]\.|\d\)|[가나다라마바사아자차카타파하]\)|\(\d\)|\([가나다라마바사아자차카타파하]\))\s)/g;
const SUBTITLE_WORDS = "판단|결론|사실관계|검토";
const SUBTITLE_RX = new RegExp(
  `(?<=(?:\\d\\.|[가나다라마바사아자차카타파하]\\.|\\d\\)|[가나다라마바사아자차카타파하]\\)|\\(\\d\\)|\\([가나다라마바사아자차카타파하]\\))\\s(?:${SUBTITLE_WORDS}))\\s+(?=\\S)`,
  "g",
);

export function reflowNumberingSafe(text: string): string {
  return text.replace(NUMBERING_RX, "\n\n").replace(SUBTITLE_RX, "\n\n");
}
