//
// ★두 가지 실수를 한 곳에서 막는다.
//   ① `\d` 의 백슬래시가 빠지면 문자 그대로 "dddd-dd-dd" 를 찾아 **모든 날짜가 거부된다.**
//      2026-09-15 실제로 그 상태로 배포돼, 기준일을 아예 못 고쳤다(셸 히어독이 백슬래시를
//      한 겹 먹었다). 정규식을 코드 안에 흩어 두면 같은 사고가 또 난다.
//   ② 형식만 보면 2026-02-31 이 통과한다 — JS 가 3월 3일로 굴려 버린다. 기준일은
//      **하루가 곧 공제 하루**라, 굴러간 날짜를 조용히 저장하면 학생 돈이 달라진다.

/** `YYYY-MM-DD` 이면서 달력에 실재하는 날짜인지. */
export function isCalendarDate(s: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  const d = new Date(`${s}T00:00:00Z`);
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === s;
}
